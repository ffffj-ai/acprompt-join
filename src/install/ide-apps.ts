// Installers for the six desktop-IDE / desktop-agent harnesses.
//
// Every one of these harnesses takes a remote (Streamable HTTP) MCP server as
// a JSON entry, but they disagree on the details, and getting it wrong is a
// silent "tools never appear" for the user:
//
//   - Cursor      : `mcpServers.<name>` with NO `type` field. Adding one is
//                   tolerated today but is not what Cursor documents.
//   - Windsurf    : `mcpServers.<name>` in ~/.codeium/windsurf/mcp_config.json.
//   - WorkBuddy   : `mcpServers.<name>` WITH `"type": "http"`, in
//                   ~/.workbuddy/mcp.json (no leading dot — see detector).
//   - Continue    : `mcpServers.<name>` in ~/.continue/config.json.
//   - OpenClaw    : `mcp.servers.<name>` (nested one level deeper), or
//                   `openclaw mcp set` which does it for you.
//   - Zed         : no config file at all — the JSON goes into the settings UI.
//
// All six are PRINT-ONLY. Nothing here writes to disk. That is deliberate:
// the schemas above were verified for "what entry does this harness accept",
// not for "what else lives in that file and how do we merge into it". The
// only two file-writers in this package (claude-code, letta) each had to go
// through readMergeableJson for the Round-3 data-loss fix; a printer cannot
// destroy a user's existing config no matter how wrong the snippet's shape is,
// and a wrong snippet is an error the user can see and report.
//
// Source of truth for each shape: `acp/public/install.sh` (case "$HARNESS"),
// which was validated against real users. Keep the two in sync.

import pc from "picocolors";
import type { HarnessInstaller } from "./shared.js";

const DOCS_URL = "https://www.acprompt.com/api/discover";

function entry(mcpUrl: string, token: string): Record<string, unknown> {
  return {
    url: mcpUrl,
    headers: { Authorization: `Bearer ${token}` },
  };
}

function pretty(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

/** Render `{ mcpServers: { acprompt: <entry> } }`. */
function mcpServersBlock(
  mcpUrl: string,
  token: string,
  extra: Record<string, unknown> = {}
): string {
  return pretty({
    mcpServers: { acprompt: { ...extra, ...entry(mcpUrl, token) } },
  });
}

function footer(restart: string): void {
  console.log("");
  console.log(pc.bold("Then:"));
  console.log(`  ${restart}`);
  console.log("");
  console.log(pc.dim(`Docs: ${DOCS_URL}`));
}

export const cursorInstaller: HarnessInstaller = async (ic) => {
  console.log(pc.bold("Cursor — edit ~/.cursor/mcp.json"));
  console.log("");
  console.log(
    pc.dim("Add this to the file's `mcpServers` object (create the file if absent):")
  );
  console.log("");
  console.log(mcpServersBlock(ic.mcpUrl, ic.token));
  footer("Quit Cursor completely (Cmd+Q / File → Exit) and reopen it.");
  return { wrote: [], printed: ["cursor-snippet"] };
};

export const workbuddyInstaller: HarnessInstaller = async (ic) => {
  console.log(pc.bold("WorkBuddy — edit ~/.workbuddy/mcp.json"));
  console.log("");
  console.log(
    pc.yellow(
      "Use mcp.json, NOT .mcp.json. The dot-file is auto-generated by WorkBuddy"
    )
  );
  console.log(
    pc.yellow("as an internal connector-proxy descriptor and gets overwritten.")
  );
  console.log("");
  console.log(pc.dim("Merge this into the `mcpServers` object:"));
  console.log("");
  console.log(mcpServersBlock(ic.mcpUrl, ic.token, { type: "http" }));
  footer(
    "Fully close WorkBuddy — close the window AND quit from the tray icon — then reopen. MCP servers only load at startup."
  );
  return { wrote: [], printed: ["workbuddy-snippet"] };
};


export const openclawInstaller: HarnessInstaller = async (ic) => {
  console.log(pc.bold("OpenClaw — prefer the CLI, fall back to the file"));
  console.log("");
  console.log(pc.dim("Run this (it writes the config for you):"));
  console.log("");
  console.log(
    `  openclaw mcp set acprompt --url ${ic.mcpUrl} --header "Authorization: Bearer ${ic.token}"`
  );
  console.log("");
  console.log(
    pc.dim("If that fails, edit ~/.openclaw/openclaw.json — note the nesting")
  );
  console.log(pc.dim("is `mcp.servers`, one level deeper than the others:"));
  console.log("");
  console.log(
    pretty({ mcp: { servers: { acprompt: entry(ic.mcpUrl, ic.token) } } })
  );
  footer("Restart the OpenClaw gateway.");
  return { wrote: [], printed: ["openclaw-snippet"] };
};


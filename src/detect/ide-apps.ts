/**
 * Every detector added in v0.1.10, in the order they are appended to
 * `ALL_DETECTORS` (after the SDK harnesses, before `generic`).
 *
 * Ordering rationale: these are HOME-scoped signals ("the app is installed"),
 * which is weaker evidence of intent than a repo dependency or a CLI the user
 * just invoked. `install` picks the first detected harness, so putting them
 * last keeps every pre-v0.1.10 selection decision byte-for-byte identical.
 * Users who have several harnesses and want a specific one pass
 * `--harness <id>`.
 */
export const IDE_APP_DETECTORS: readonly HarnessDetector[] = [
  cursorDetector,
  workbuddyDetector,
  windsurfDetector,
  zedDetector,
  openclawDetector,
  continueDetector,
];

// Desktop-IDE / desktop-agent harness detectors.
//
// These six harnesses all keep their MCP config in a per-user file (or, for
// Zed, only in its settings UI), so detection is "does that file / directory
// exist, or is the CLI on PATH". No process is spawned — see which.ts.
//
// Authoritative source for every path below: `acp/src/lib/harness-quirks.ts`
// (`HARNESS_CONFIG_TABLE`) and `acp/public/install.sh` (`case "$HARNESS"`),
// both of which were verified against real installs. Do not "improve" a path
// from memory — a wrong path means we tell the user to edit a file their
// harness never reads.
//
// Why these were missing until v0.1.10: the npm installer only ever carried
// detectors for claude-code + the Python/JS SDK harnesses, while
// `install.sh` already advertised `cursor, windsurf, zed, openclaw, continue,
// workbuddy` as auto-detectable. Users of those harnesses ran
// `npx @acprompt/join`, were told "No specific harness matched", and got a
// generic snippet instead of their real config path.

import { promises as fs } from "node:fs";
import path from "node:path";
import type {
  DetectionContext,
  DetectionResult,
  HarnessDetector,
} from "./types.js";
import { findExecutableOnPath } from "./which.js";

interface IdeAppSpec {
  readonly id: string;
  readonly label: string;
  /**
   * Absolute path of the MCP config file the user must edit.
   * `null` for UI-only harnesses (Zed), which have no file to point at.
   */
  configPath(ctx: DetectionContext): string | null;
  /** Directories that appear once the app has been installed/run. */
  appDirs(ctx: DetectionContext): string[];
  /** Binary names to look for on PATH. Never executed. */
  binNames: readonly string[];
  /** One line shown in `detect` when nothing matched. */
  readonly missingReason: string;
}

async function fileExists(p: string): Promise<boolean> {
  try {
    const s = await fs.stat(p);
    return s.isFile();
  } catch {
    return false;
  }
}

async function dirExists(p: string): Promise<boolean> {
  try {
    const s = await fs.stat(p);
    return s.isDirectory();
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// Paths. Exported so tests (and future installers) pin the exact strings.
// ---------------------------------------------------------------------------

export function cursorConfigPath(ctx: DetectionContext): string {
  return path.join(ctx.home, ".cursor", "mcp.json");
}

export function workbuddyConfigPath(ctx: DetectionContext): string {
  // NO leading dot on mcp.json. `~/.workbuddy/.mcp.json` is auto-generated by
  // WorkBuddy as an internal connector-proxy descriptor; user config written
  // there is overwritten on the next restart. Verified 2026-05-04.
  return path.join(ctx.home, ".workbuddy", "mcp.json");
}

export function windsurfConfigPath(ctx: DetectionContext): string {
  return path.join(ctx.home, ".codeium", "windsurf", "mcp_config.json");
}

export function openclawConfigPath(ctx: DetectionContext): string {
  return path.join(ctx.home, ".openclaw", "openclaw.json");
}

export function continueConfigPath(ctx: DetectionContext): string {
  return path.join(ctx.home, ".continue", "config.json");
}

export function zedConfigDir(ctx: DetectionContext): string {
  return path.join(ctx.home, ".config", "zed");
}

// ---------------------------------------------------------------------------
// Factory
// ---------------------------------------------------------------------------

function makeIdeAppDetector(spec: IdeAppSpec): HarnessDetector {
  return {
    id: spec.id,
    label: spec.label,

    async detect(ctx: DetectionContext): Promise<DetectionResult> {
      const configPath = spec.configPath(ctx);
      const configTargets = configPath ? [configPath] : [];

      try {
        const evidence: string[] = [];

        if (configPath && (await fileExists(configPath))) {
          evidence.push(`${spec.label} MCP config: ${configPath}`);
        }

        for (const dir of spec.appDirs(ctx)) {
          if (await dirExists(dir)) {
            evidence.push(`${spec.label} app dir: ${dir}`);
          }
        }

        const bin = await findExecutableOnPath(ctx, spec.binNames);
        if (bin) {
          evidence.push(`${spec.binNames.join("|")} on PATH: ${bin}`);
        }

        if (evidence.length === 0) {
          return {
            harness: spec.id,
            label: spec.label,
            detected: false,
            reason: spec.missingReason,
            configTargets,
          };
        }

        return {
          harness: spec.id,
          label: spec.label,
          detected: true,
          evidence,
          configTargets,
        };
      } catch (e) {
        // Detectors must never throw — a single failure would be swallowed by
        // Promise.all's caller and could hide the whole report.
        return {
          harness: spec.id,
          label: spec.label,
          detected: false,
          reason: (e as Error).message,
          configTargets,
        };
      }
    },
  };
}

